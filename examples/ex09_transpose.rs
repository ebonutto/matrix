use matrix::Matrix;

fn main() {
    let u = Matrix::from([[1., 0.], [0., 1.]]);
    println!("{}", u.transpose());
    // [1.0, 0.0]
    // [0.0, 1.0]

    let u = Matrix::from([[2., -5., 0.], [4., 3., 7.], [-2., 3., 4.]]);
    println!("{}", u.transpose());
    // [2.0, 4.0, -2.0]
    // [-5.0, 3.0, 3.0]
    // [0.0, 7.0, 4.0]

    let u = Matrix::from([[-2., -8., 4.], [1., -23., 4.], [0., 6., 4.]]);
    println!("{}", u.transpose());
    // [-2.0, 1.0, 0.0]
    // [-8.0, -23.0, 6.0]
    // [4.0, 4.0, 4.0]
}
